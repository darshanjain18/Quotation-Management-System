import { jsPDF } from 'jspdf'
import autoTable from 'jspdf-autotable'
import { formatINR } from '../../../utils/money'

function formatDate(value) {
  if (!value) return '—'
  return new Date(`${value}T00:00:00`).toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  })
}

export function getQuotationPdfFilename(quotation) {
  const number = String(quotation?.quotation_number || 'quotation')
    .replace(/[^\w.-]+/g, '_')
    .replace(/_+/g, '_')
  return `${number}.pdf`
}

/**
 * Generate and download a professional quotation PDF.
 */
export function exportQuotationPdf(quotation) {
  if (!quotation) throw new Error('Quotation is required')

  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const marginX = 48
  let y = 56

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(18)
  doc.text('QMS', marginX, y)

  doc.setFontSize(11)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(80)
  doc.text('Quotation', marginX, y + 18)

  doc.setTextColor(20)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(14)
  doc.text(String(quotation.quotation_number || ''), 547, y, { align: 'right' })
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.setTextColor(90)
  doc.text(`Date: ${formatDate(quotation.quotation_date)}`, 547, y + 16, { align: 'right' })
  doc.text(`Valid until: ${formatDate(quotation.valid_until)}`, 547, y + 30, { align: 'right' })

  y = 120
  doc.setTextColor(20)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(11)
  doc.text('Bill To', marginX, y)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  const customerLines = [
    quotation.customer_name,
    quotation.company_name,
    quotation.email,
    quotation.phone,
  ].filter(Boolean)

  customerLines.forEach((line, index) => {
    doc.text(String(line), marginX, y + 16 + index * 14)
  })

  const items = quotation.quotation_items || []
  autoTable(doc, {
    startY: y + 16 + customerLines.length * 14 + 24,
    head: [['Product / Service', 'Qty', 'Unit Price', 'Discount', 'Amount']],
    body: items.map((item) => [
      item.product_name || '',
      String(Number(item.quantity)),
      formatINR(item.unit_price),
      `${Number(item.discount)}%`,
      formatINR(item.amount),
    ]),
    styles: {
      font: 'helvetica',
      fontSize: 9,
      cellPadding: 6,
    },
    headStyles: {
      fillColor: [37, 99, 235],
      textColor: 255,
      fontStyle: 'bold',
    },
    columnStyles: {
      1: { halign: 'right' },
      2: { halign: 'right' },
      3: { halign: 'right' },
      4: { halign: 'right' },
    },
    margin: { left: marginX, right: marginX },
  })

  const totalsY = (doc.lastAutoTable?.finalY || 200) + 20
  const labelX = 360
  const valueX = 547

  const rows = [
    ['Subtotal', formatINR(quotation.subtotal)],
    [`GST (${Number(quotation.gst_rate)}%)`, formatINR(quotation.gst)],
    ['Grand Total', formatINR(quotation.total)],
  ]

  rows.forEach(([label, value], index) => {
    const rowY = totalsY + index * 18
    const isTotal = index === rows.length - 1
    doc.setFont('helvetica', isTotal ? 'bold' : 'normal')
    doc.setFontSize(isTotal ? 11 : 10)
    doc.setTextColor(isTotal ? 20 : 90)
    doc.text(label, labelX, rowY)
    doc.setTextColor(20)
    doc.text(value, valueX, rowY, { align: 'right' })
  })

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.setTextColor(130)
  doc.text('Generated by QMS', marginX, 812)

  doc.save(getQuotationPdfFilename(quotation))
}
